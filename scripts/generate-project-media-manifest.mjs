import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const supportedExtensions = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png"]);
const coverPreference = [".webp", ".avif", ".jpg", ".jpeg", ".png"];

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const defaultProjectsRoot = path.join(repoRoot, "public", "projects");
const defaultOutputPath = path.join(repoRoot, "app", "data", "project-media-manifest.generated.ts");

function toPublicUrl(projectFolder, relativeFilePath) {
  return `/projects/${projectFolder}/${relativeFilePath.split(path.sep).join("/")}`;
}

async function pathExists(filePath) {
  try {
    await readdir(filePath);
    return true;
  } catch {
    return false;
  }
}

async function collectImageFiles(directory, baseDirectory = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(directory, entry.name);

      if (entry.isDirectory()) {
        return collectImageFiles(fullPath, baseDirectory);
      }

      if (!entry.isFile() || !supportedExtensions.has(path.extname(entry.name).toLowerCase())) {
        return [];
      }

      return [path.relative(baseDirectory, fullPath)];
    }),
  );

  return files.flat();
}

function sortMediaPaths(files) {
  return [...files].sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));
}

function pickCover(files) {
  const covers = files.filter((file) => {
    const parsed = path.parse(file);
    return !file.includes(path.sep) && parsed.name.toLowerCase() === "cover";
  });

  return covers.sort(
    (a, b) =>
      coverPreference.indexOf(path.extname(a).toLowerCase()) -
      coverPreference.indexOf(path.extname(b).toLowerCase()),
  )[0];
}

function renderManifest(manifest) {
  return `// This file is generated by scripts/generate-project-media-manifest.mjs.
// Do not edit it by hand. Add images under public/projects/{assetFolder}/ instead.

export type GeneratedProjectMediaEntry = {
  cover?: string;
  gallery: string[];
};

export const generatedProjectMediaManifest: Record<string, GeneratedProjectMediaEntry> = ${JSON.stringify(manifest, null, 2)};
`;
}

export async function generateProjectMediaManifest({
  projectsRoot = defaultProjectsRoot,
  outputPath = defaultOutputPath,
} = {}) {
  const manifest = {};

  if (await pathExists(projectsRoot)) {
    const projectDirectories = await readdir(projectsRoot, { withFileTypes: true });

    for (const entry of projectDirectories) {
      if (!entry.isDirectory()) {
        continue;
      }

      const projectFolder = entry.name;
      const projectPath = path.join(projectsRoot, projectFolder);
      const files = sortMediaPaths(await collectImageFiles(projectPath));
      const cover = pickCover(files);
      const gallery = files
        .filter((file) => file.split(path.sep)[0] === "gallery")
        .map((file) => toPublicUrl(projectFolder, file));

      manifest[projectFolder] = {
        ...(cover ? { cover: toPublicUrl(projectFolder, cover) } : {}),
        gallery,
      };
    }
  }

  const nextContents = renderManifest(manifest);
  await mkdir(path.dirname(outputPath), { recursive: true });

  let previousContents = "";
  try {
    previousContents = await readFile(outputPath, "utf8");
  } catch {
    // The first run creates the generated manifest.
  }

  if (previousContents !== nextContents) {
    await writeFile(outputPath, nextContents);
  }

  return manifest;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateProjectMediaManifest();
}
